# STEP 1 — Your AI usage (sidebar)
# =====================================================================
sb = st.sidebar
sb.title("🖥️ GPU Sizing")
sb.caption("Cloud vs on-prem inference — TCO, break-even, savings")
sb.markdown("---")
sb.header("1 · Your AI usage")

preset = sb.selectbox(
    "Usage intensity (per user)",
    list(INTENSITY_PRESETS),
    format_func=lambda k: INTENSITY_PRESETS[k]["label"],
)
P = INTENSITY_PRESETS[preset]

users = sb.number_input("Users", 1, 1_000_000, 25, step=1,
                        help="People whose AI workload you want to serve.")
in_tpu = sb.number_input(
    "Input tokens / user / day", 0, 10_000_000_000, int(P["in"]), step=100_000,
    key=f"in_{preset}",
    help="Prompts + context sent to the model, per user per day.",
)
out_tpu = sb.number_input(
    "Output tokens / user / day", 0, 1_000_000_000, int(P["out"]), step=10_000,
    key=f"out_{preset}",
    help="Tokens generated by the model, per user per day.",
)
workdays = sb.number_input("Active days / month", 1.0, 31.0, 22.0, step=1.0,
                           help="22 ≈ business days; 30 for always-on teams.")
growth = sb.number_input(
    "Demand growth / month (%)", -10.0, 50.0, 0.0, step=0.5,
    help="Expect usage to grow (or shrink) month over month.",
)

sb.markdown("---")
sb.header("Cloud comparison")

model = sb.selectbox(
    "Cloud model (list pricing)",
    [m["key"] for m in CLOUD_MODELS],
    format_func=lambda k: f"{CLOUD_BY_KEY[k]['label']} — "
                          f"${CLOUD_BY_KEY[k]['input']:g}/M in, "
                          f"${CLOUD_BY_KEY[k]['output']:g}/M out",
)
M = CLOUD_BY_KEY[model]
ci = sb.number_input("Cloud $ / 1M input tokens", 0.0, 9999.0,
                     float(M["input"]), step=0.1, key=f"ci_{model}")
co = sb.number_input("Cloud $ / 1M output tokens", 0.0, 9999.0,
                     float(M["output"]), step=0.1, key=f"co_{model}")

with sb.expander("Adjustments (cache, batch, overhead)"):
    cache_hit = sb.number_input("Prompt-cache hit rate (%)", 0.0, 100.0, 0.0, step=5.0,
                                help="Cached input tokens are billed at ~10% of base.")
    batch_disc = sb.number_input("Batch / off-peak discount (%)", 0.0, 90.0, 0.0, step=5.0)
    overhead = sb.number_input("Platform overhead (%)", 0.0, 100.0, 0.0, step=5.0,
                               help="Data transfer, platform fees, margin on cloud spend.")
    fixed_fee = sb.number_input("Fixed cloud fees ($/month)", 0.0, 1_000_000.0, 0.0, step=10.0)

    use_mix = sb.checkbox("Use a model mix (weighted average pricing)", value=False)
    mix_users = {}
    if use_mix:
        mix_users = sb.markdown("")  # placeholder to keep layout stable
        cols = sb.columns(2)
        mix_users = {}
        for i, m in enumerate(CLOUD_MODELS):
            with cols[i % 2]:
                mix_users[m["key"]] = sb.number_input(
                    f"Users → {m['label']}", 0, 1_000_000, 0, key=f"mix_{model}_{m['key']}",
                )
        if sum(mix_users.values()) == 0:
            sb.caption("No mix users set — using the single model above.")

sb.markdown("---")
sb.header("Coverage")
local_share = sb.slider(
    "Workload served by your GPUs (%)", 0, 100, 100, step=5,
    help="Hybrid mode: the remainder stays on the cloud API. 100% = all-local.")

# ---- resolve weighted pricing -------------------------------------
pricing = CloudPricing(
    input_price=ci,
    output_price=co,
    cache_hit_pct=cache_hit,
    batch_discount_pct=batch_disc,
    overhead_pct=overhead,
    fixed_monthly=fixed_fee,
)
if use_mix and mix_users and sum(mix_users.values()) > 0:
    total = sum(mix_users.values())
    pricing = CloudPricing(
        input_price=sum(mix_users[m["key"]] * m["input"] for m in CLOUD_MODELS) / total,
        output_price=sum(mix_users[m["key"]] * m["output"] for m in CLOUD_MODELS) / total,
        cache_hit_pct=cache_hit,
        batch_discount_pct=batch_disc,
        overhead_pct=overhead,
        fixed_monthly=fixed_fee,
    )

demand = Demand(
    users=int(users),
    input_tpd_per_user=float(in_tpu),
    output_tpd_per_user=float(out_tpu),
    workdays_per_month=float(workdays),
    growth_pct_per_month=float(growth),
)

monthly_in = demand.in_daily * demand.workdays_per_month
monthly_out = demand.out_daily * demand.workdays_per_month

# =====================================================================
# STEP 2 — Hardware & results (main)
# =====================================================================
st.title("GPU Sizing & Cloud Savings")
st.caption(
    "Compare running your AI workload on owned GPUs vs cloud API spend. "
    "Sizing, TCO, break-even and savings over a chosen period."
)

h1, h2, h3, h4 = st.columns(4)
gpu_key = h1.selectbox(
    "GPU", [g["key"] for g in GPU_PRESETS],
    format_func=lambda k: GPU_BY_KEY[k]["label"],
)
G = GPU_BY_KEY[gpu_key]
price = h2.number_input("Price ($/unit)", 100.0, 1_000_000.0, float(G["price"]), step=100.0,
                        key=f"price_{gpu_key}")
watts = h3.number_input("Power (W)", 25.0, 4000.0, float(G["watts"]), step=10.0,
                        key=f"watts_{gpu_key}")
cap_in = h4.number_input("Sustained in tok/s/GPU", 1.0, 1_000_000.0, float(G["in_tps"]),
                         step=10.0, key=f"intps_{gpu_key}",
                         help="Prefill throughput. Calibrate to your own vLLM benchmark — this is the biggest lever in the calc.")
cap_out = h4.number_input("Sustained out tok/s/GPU", 0.1, 100_000.0, float(G["out_tps"]),
                          step=1.0, key=f"outtps_{gpu_key}",
                          help="Decode throughput per GPU at your model size.")

p1, p2, p3, p4, p5 = st.columns(5)
elec = p1.number_input("Electricity ($/kWh)", 0.0, 5.0, 0.15, step=0.01)
pue = p2.number_input("PUE", 1.0, 3.0, 1.2, step=0.05)
duty = p3.number_input("Duty hours/day", 1.0, 24.0, 24.0, step=1.0)
pdays = p4.number_input("Power days/month", 1.0, 31.0, 30.0, step=1.0)
hosting = p5.number_input("Maintenance ($/GPU/mo)", 0.0, 10_000.0, 50.0, step=10.0)

o1, o2, o3, o4 = st.columns(4)
target_util = o1.number_input("Target utilization (%)", 10.0, 95.0, 70.0, step=5.0,
                              help="Size the fleet so demand uses ≤ this share of capacity.")
life = o2.number_input("Hardware life (months)", 6, 120, 36, step=6)
residual = o3.number_input("Residual value at end of life (%)", 0.0, 100.0, 20.0, step=5.0)
disc = o4.number_input("Discount rate (%/yr)", 0.0, 30.0, 8.0, step=1.0)

st.markdown("---")

months = st.slider("Comparison period (months)", 6, 120, 36, step=6)

gpu = GpuSpec(gpu_key, GPU_BY_KEY[gpu_key]["label"], float(price), float(watts),
              float(cap_in), float(cap_out))
own = Ownership(
    duty_hours_per_day=float(duty),
    power_days_per_month=float(pdays),
    pue=float(pue),
    elec_rate=float(elec),
    hosting_per_gpu_month=float(hosting),
    target_utilization_pct=float(target_util),
    hardware_life_months=int(life),
    residual_pct=float(residual),
    discount_rate_pct=float(disc),
)

res = simulate(demand, pricing, gpu, own, int(months), local_share / 100.0)

# ---------------------------------------------------------------- KPIs
be = res["break_even_month"]
st.header("2 · Your results")

k1, k2, k3, k4, k5, k6 = st.columns(6)
k1.metric(
    "Break-even (vs all-cloud)",
    f"Month {be}" if be else f"> {int(months)} mo",
    help="First month where cumulative local cost falls below cumulative cloud spend.",
)
k2.metric(
    f"Savings over {int(months)} mo",
    usd(res["savings"]),
    delta=f"{res['savings_pct']:+.1f}% vs all-cloud" if res["cloud_full_total"] else None,
)
k3.metric("Local TCO (period)", usd(res["tco"]),
          help="Total cost of ownership: capex + opex − terminal fleet value.")
k4.metric("All-cloud cost (period)", usd(res["cloud_full_total"]))
k5.metric("GPUs required (peak)", f"{res['peak_units']}")
k6.metric("Cloud run-rate (final mo)", usd(res["cloud_last"]["total"]),
          help="What the cloud would charge for the portion not covered locally, at month end.")

# ---------------------------------------------------------------- charts
fig = go.Figure()
