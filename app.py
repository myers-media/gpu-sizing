s1, s2, s3, s4 = st.columns(4)
s1.metric("GPUs at month 1", f"{res['units_month1']}")
s2.metric("Utilization @ peak", f"{res['peak_utilization']*100:.0f}%")
s3.metric("Energy / GPU / month", usd(res["energy_per_gpu_month"]))
s4.metric("NPV of local path", usd(res["npv"]),
          help="Time-discounted TCO at the chosen discount rate.")

# ---------------------------------------------------------------- detail
with st.expander("Cost calculation detail", expanded=False):
    d1, d2 = st.columns(2)
    last_m = int(months)
    with d1:
        st.markdown("**Cloud (final month, full workload)**")
        cl = res["cloud_last"]
        tbl = pd.DataFrame(
            {
                "": ["Input tokens / mo", "Output tokens / mo",
                     "Input cost", "Output cost", "Adjustments (cache/batch/overhead)",
                     "Total (incl. fixed fees)"],
                "Value": [
                    f"{cl['tokens_in']/1e6:,.1f} M",
                    f"{cl['tokens_out']/1e6:,.1f} M",
                    usd_full(cl["input"]),
                    usd_full(cl["output"]),
                    usd_full(cl["total"] - cl["input"] - cl["output"]),
                    usd_full(cl["total"]),
                ],
            }
        )
        st.dataframe(tbl, width="stretch", hide_index=True)
    with d2:
        st.markdown("**Local fleet (period totals)**")
        tbl2 = pd.DataFrame(
            {
                "": ["Hardware purchases (gross)", "Resale credits",
                     "Terminal fleet value", "Energy (period)",
                     "Maintenance/hosting", "TCO (purchases + opex − terminal)",
                     "NPV"],
                "Value": [
                    usd_full(res["gross_purchases"]),
                    usd_full(res["retirement_credits"]),
                    usd_full(res["terminal_value"]),
                    usd_full(sum(o - a * own.hosting_per_gpu_month
                                 for o, a in zip(res["hybrid_opex"], res["hybrid_units"]))),
                    usd_full(sum(a * own.hosting_per_gpu_month
                                 for a in res["hybrid_units"])),
                    usd_full(res["tco"]),
                    usd_full(res["npv"]),
                ],
            }
        )
        st.dataframe(tbl2, width="stretch", hide_index=True)

    st.markdown("**Paths over the period**")
    tbl3 = pd.DataFrame(
        {
            "Path": ["All cloud", "All local",
                     f"Hybrid ({int(res['local_share']*100)}% local)"],
            "Total cost": [usd(res["cloud_full_total"]), usd(res["local_full_total"]),
                           usd(res["hybrid_total"])],
            "Savings vs all-cloud": ["—", usd(res["cloud_full_total"] - res["local_full_total"]),
                                     usd(res["savings"])],
        }
    )
    st.dataframe(tbl3, width="stretch", hide_index=True)

with st.expander("Sensitivity — break-even under other assumptions", expanded=False):
    rows = sensitivity(res, demand, pricing, gpu, own, int(months), local_share / 100.0)
    st.dataframe(
        pd.DataFrame(
            {
                "Scenario": [r["label"] for r in rows],
                "Assumptions": [r["note"] for r in rows],
                "Break-even": [
                    f"Month {r['break_even']}" if r["break_even"] else f"> {int(months)} mo"
                    for r in rows
                ],
            }
        ),
        width="stretch", hide_index=True,
    )

