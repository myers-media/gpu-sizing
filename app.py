"""GPU Sizing & Cloud Savings Calculator.

Streamlit front-end modeled on AMD's AI Cost Calculator (tokenomics.amd.com):
  Step 1 (sidebar):  your AI usage — token intensity, growth, cloud pricing
  Step 2 (main):     your results — GPU sizing, TCO vs cloud, break-even, savings

Run:  streamlit run app.py --server.port 8765 --server.address 0.0.0.0
"""

